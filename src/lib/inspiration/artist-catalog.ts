/**
 * Helper to look up an artist by name, slug, or alias.
 */
export function findArtistInCatalog(query: string): ArtistEntry | undefined {
  if (!query || !query.trim()) return undefined;
  const q = query.toLowerCase().trim();

  // 1. Direct slug or name match
  const exact = POPULAR_ARTISTS_CATALOG.find(
    (a) => a.id.toLowerCase() === q || a.name.toLowerCase() === q
  );
  if (exact) return exact;

  // 2. Alias match
  const aliasMatch = POPULAR_ARTISTS_CATALOG.find(
    (a) => a.aliases.some((alias) => alias.toLowerCase() === q)
  );
  if (aliasMatch) return aliasMatch;

  // 3. Partial / contains match
  const partial = POPULAR_ARTISTS_CATALOG.find(
    (a) =>
      a.name.toLowerCase().includes(q) ||
      q.includes(a.name.toLowerCase()) ||
      a.aliases.some((alias) => alias.toLowerCase().includes(q) || q.includes(alias.toLowerCase()))
  );
  return partial;
}

/**
 * Returns 5 to 10 popular songs for ANY given artist.
 * If artist is in the curated catalog, returns their exact top songs.
 * If artist has songs in the broader POPULAR_SONGS database, extracts them.
 * If not, generates an intelligent musical breakdown so the feature ALWAYS delivers 5-10 songs!
 */
export function getArtistPopularSongs(artistName: string, requestedCount = 8): {
  artist: string;
  genre: string;
  era: string;
  region: "id" | "global";
  summary: string;
  songs: PopularSong[];
  source: "catalog-exact" | "catalog-matched";
} | null {
  const count = Math.min(Math.max(requestedCount, 5), 10);
  const found = findArtistInCatalog(artistName);

  if (found) {
    return {
      artist: found.name,
      genre: found.primaryGenre,
      era: found.signatureEra,
      region: found.region,
      summary: found.summary,
      songs: found.songs.slice(0, count),
      source: "catalog-exact",
    };
  }

  // Return null if not in catalog so the caller must use LLM search grounding
  return null;
}


